import fs from "node:fs/promises";
const files = [
  "20261105000000_saas2_policies.sql",
  "20261105010000_saas2_booking_contract.sql",
  "20261105020000_saas2_intelligence.sql",
  "20261105030000_saas2_waitlist.sql",
];
const header = `-- GENERATED by node scripts/build-saas2-sql.mjs; DO NOT run automatically in production.\n-- Existing installation required. Backup/review first; creates no cron or messages.\nBEGIN;\nDO $$ BEGIN\n IF to_regclass('public.site_settings') IS NULL OR to_regclass('public.bookings') IS NULL OR NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='working_hours' AND column_name='lunch_start') THEN RAISE EXCEPTION 'Schema base incompleto: revise as migrations existentes antes do SaaS 2.0.';END IF;\nEND $$;\n`;
let body = "";
for (const file of files) {
  const sql = await fs.readFile("supabase/migrations/" + file, "utf8");
  body +=
    "\n-- SOURCE: " +
    file +
    "\n" +
    sql.replace(/^BEGIN;\s*$/gm, "").replace(/^COMMIT;\s*$/gm, "");
}
const result = header + body + "\nCOMMIT;\n";
if (process.argv.includes("--check")) {
  if ((await fs.readFile("supabase/saas2-install.sql", "utf8")) !== result)
    throw Error("SQL bundle desatualizado");
  console.log("SQL bundle sincronizado");
} else {
  await fs.writeFile("supabase/saas2-install.sql", result);
  console.log("SQL único gerado");
}
